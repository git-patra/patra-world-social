import {test,expect} from '@playwright/test';
import {randomBytes} from 'node:crypto';

test('register, log in, log out, and recover with a disposable account',async({page})=>{
 const username=`e2e_${randomBytes(6).toString('hex')}`;
 const password=`LocalTest!${randomBytes(16).toString('base64url')}`;
 const nextPassword=`NextLocal!${randomBytes(16).toString('base64url')}`;
 await page.goto('/');
 await expect(page.locator('#world')).toBeVisible();
 await page.getByRole('button',{name:'Buka akun'}).click();
 await page.getByRole('button',{name:'Daftar',exact:true}).click();
 await page.getByLabel('Nama pengguna').fill(username);
 await page.getByLabel('Kata sandi',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Buat akun',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Kode pemulihan'})).toBeVisible();
 const firstCode=await page.locator('#recovery-output').inputValue();
 expect(firstCode.length).toBeGreaterThanOrEqual(40);
 await page.getByRole('button',{name:'Sudah kusimpan'}).click();
 await page.getByLabel('Nama pengguna').fill(username);
 await page.getByLabel('Kata sandi',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Masuk ke desa',exact:true}).click();
 await expect(page.locator('#account-label')).toHaveText(`@${username}`);
 await page.locator('#account-button').click();
 await page.getByRole('button',{name:'Keluar akun'}).click();
 await expect(page.locator('#account-label')).toHaveText('Akun');
 await page.getByRole('button',{name:'Pulihkan',exact:true}).click();
 await page.getByLabel('Nama pengguna').fill(username);
 await page.getByLabel('Kode pemulihan').fill(firstCode);
 await page.getByLabel('Kata sandi baru').fill(nextPassword);
 await page.getByRole('button',{name:'Pulihkan akun',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Kode pemulihan'})).toBeVisible();
 const secondCode=await page.locator('#recovery-output').inputValue();
 expect(secondCode).not.toBe(firstCode);
 await page.getByRole('button',{name:'Sudah kusimpan'}).click();
 await page.getByLabel('Nama pengguna').fill(username);
 await page.getByLabel('Kata sandi',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Masuk ke desa',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('salah');
 await page.getByLabel('Kata sandi',{exact:true}).fill(nextPassword);
 await page.getByRole('button',{name:'Masuk ke desa',exact:true}).click();
 await expect(page.locator('#account-label')).toHaveText(`@${username}`);
});
